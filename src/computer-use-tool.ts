import { isProjectTrusted } from "@amaster.ai/pi-shared/settings";
import { defineTool, type ExtensionAPI } from "@earendil-works/pi-coding-agent";
import { Type } from "typebox";
import { loadClassifierSettings } from "./config.js";
import { runComputerUse, DRIVER_TOOLS } from "./computer-use.js";
import { KEY_NAMES } from "./computer-use-state.js";
import { ClassifierError, isRecord, userError } from "./types.js";
import type { ComputerUseParams, DriverReply } from "./computer-use-types.js";

const selector = Type.Object({ role: Type.String({ minLength: 1, maxLength: 128 }), label: Type.String({ minLength: 1, maxLength: 512 }) }, { additionalProperties: false });
const id = Type.String({ pattern: "^[a-zA-Z0-9_-]{1,64}$" });
const control = Type.Union([
  Type.Object({ id, selector, operation: Type.Literal("click") }, { additionalProperties: false }),
  Type.Object({ id, selector, operation: Type.Literal("fill"), valueKey: id }, { additionalProperties: false }),
  Type.Object({ id, selector, operation: Type.Literal("key"), key: Type.Union(KEY_NAMES.map((k) => Type.Literal(k))) }, { additionalProperties: false }),
]);
const expectation = Type.Object({ element: Type.Object({
  selector: Type.Object({ role: Type.String({ minLength: 1, maxLength: 128 }), label_contains: Type.String({ minLength: 1, maxLength: 512 }) }, { additionalProperties: false }),
  exists: Type.Optional(Type.Literal(true)),
  value_equals: Type.Optional(Type.String({ maxLength: 4096 })),
  enabled: Type.Optional(Type.Boolean()), selected: Type.Optional(Type.Boolean()),
}, { additionalProperties: false }) }, { additionalProperties: false });

export const computerUseParameters = Type.Object({
  goal: Type.String({ minLength: 1, maxLength: 4096 }),
  target: Type.Object({ pid: Type.Integer({ minimum: 1 }), window_id: Type.Integer({ minimum: 0 }) }, { additionalProperties: false }),
  controls: Type.Array(control, { minItems: 1, maxItems: 120, description: "Only controls authorized for this goal. Exact role and label; controls may span later screens. This is an allowlist, not an ordered script. Never include unapproved consequential or credential actions." }),
  values: Type.Optional(Type.Record(id, Type.String({ maxLength: 4096 }), { maxProperties: 64, description: "Supplied nonsecret single-line text, never generated by Decisions. Missing values hand back. Do not include credentials." })),
  expect: Type.Optional(Type.Array(expectation, { minItems: 1, maxItems: 8, description: "All predicates must cover the full desired outcome. Without them DONE hands back for supervisor verification." })),
  context: Type.Optional(Type.String({ maxLength: 4096, description: "Supervisor note after a handoff or unsupported action; not evidence of completion or new authorization." })),
  previousActions: Type.Optional(Type.Array(Type.String({ maxLength: 256 }), { maxItems: 20 })),
  maxActions: Type.Optional(Type.Integer({ minimum: 1, maximum: 100 })),
  timeoutMs: Type.Optional(Type.Integer({ minimum: 1000, maximum: 300000 })),
  deliveryMode: Type.Optional(Type.Union([Type.Literal("background"), Type.Literal("foreground")], { description: "Default background. Choose foreground only after observed background failure, within the same authorized target and scope." })),
}, { additionalProperties: false });

export function registerComputerUseTool(pi: ExtensionAPI): void {
  let running = false;
  pi.registerTool(defineTool({
    name: "classifier_computer_use",
    label: "Computer use · Decisions",
    description: "Run a bounded OpenAI Decisions observe/select/act/verify loop on one exact Cua Driver window. Uses configured pi-classifier.computerUse, never the generic classifier default. Supply permitted semantic controls and nonsecret typing values. Decisions chooses from grounded candidates; it cannot invent coordinates or text. Returns explicit handoff and continuation when supervisor help is needed. Completion requires fresh independent Driver predicates; otherwise needs_verification. Existing Driver permissions and Pi tool hooks remain active. Window text and optional screenshots are sent to the configured OpenAI endpoint.",
    promptSnippet: "Delegate repeated permitted computer actions to OpenAI Decisions; handle explicit supervisor handoffs and independently verify outcomes.",
    promptGuidelines: [
      "Resolve the intended app/account/window and observe semantic control names before calling. Supply only controls and effects authorized by the user's goal; an allowlist is not user consent.",
      "Keep the goal bounded and values nonsecret. Keep content generation, credentials, CAPTCHAs, unsupported surfaces and consequential approvals with the supervisor or user.",
      "On handoff inspect the reason, attempted actions and current state. Supply missing values or perform the unsupported step, then call again using handoff.continuation with an updated context note. Never replay a possibly applied action blindly.",
      "Do not call other tools that observe or mutate the same window concurrently. Every continuation reobserves; never pass element tokens, screenshots or pending actions between chunks.",
      "Only report verified completion when expect covers the whole user goal. Without independent predicates, inspect fresh evidence after needs_verification. Do not lower confidence or change provider to force progress.",
    ],
    parameters: computerUseParameters,
    outputSchema: Type.Object({ status: Type.Union([Type.Literal("completed"), Type.Literal("handoff"), Type.Literal("stopped")]) }, { additionalProperties: true }),
    reachesTools: () => Object.values(DRIVER_TOOLS),
    annotations: { readOnlyHint: false, destructiveHint: true, openWorldHint: true },
    async execute(_id, params, signal, onUpdate, ctx) {
      if (running) throw new Error("Another computer-use chunk is running in this extension. Serialize access to the desktop.");
      running = true;
      try {
        const result = await runComputerUse(params as ComputerUseParams, {
          settings: loadClassifierSettings(ctx.cwd, isProjectTrusted(ctx)), cwd: ctx.cwd, ...(signal ? { signal } : {}),
          callTool: async (name, args, nestedSignal): Promise<DriverReply> => {
            const outcome = await ctx.executeTool(name, args, { signal: nestedSignal });
            // Pi's MCP wrapper exposes the raw CallToolResult inside result.structuredContent.
            const raw = outcome.result.structuredContent;
            if (outcome.isError || !isRecord(raw)) return { isError: true };
            return raw as DriverReply;
          },
          onProgress: (progress) => onUpdate?.({ content: [{ type: "text", text: `${progress.phase}: ${progress.actions} actions, ${progress.decisions} decisions` }], details: progress }),
        });
        return { content: [{ type: "text", text: JSON.stringify(result) }], details: result, structuredContent: JSON.parse(JSON.stringify(result)) };
      } catch (error) {
        throw new Error(error instanceof ClassifierError ? userError(error) : "Computer use could not start. Check computerUse settings and Driver availability.");
      } finally { running = false; }
    },
  }));
}
